"""Jev vs Gemini 3.8 Flash vs Claude Opus 5.5 on all 8 tasks (no API calls).

Reads results/v1/pred_*.csv (Jev), results/v1/gem_*.csv (Gemini), results/v1/opus_*.csv (Opus) for zero-shot and in-context,
and results/v1/platt_constrained.csv for Platt (study.py's Platt, falling back to a base-rate shift when the fit is flat
or inverted). Draws 0-1, same 300 test cases.

Outputs:
  results/v1/compare_3models.md   mean prediction (AUROC) per k, plus a Brier table with paired bootstrap CIs
  results/v1/compare_opus_ci.csv  Brier/AUROC values and Opus-Jev, Opus-Gemini differences at k=0 and k=100
Bootstrap: resample test cases and draws jointly (B=2000), as compare_ci.py (analyze2.py uses the same scheme with B=1000).
"""
import os

import numpy as np
import pandas as pd

from analyze import auroc, brier
from tasks import ROOT, load

OUT = os.path.join(ROOT, "results", "v1")
B = 2000
DRAWS = [0, 1]
KS = [5, 20, 100]
TASK_ORDER = ["nyc311", "crimes", "flights", "shelter", "stackoverflow", "hn", "github_prs", "inspections"]
MODELS = {"Jev": "pred", "Gemini": "gem", "Opus": "opus"}
LABEL = {"Jev": "Jev", "Gemini": "Gemini 3.8 Flash", "Opus": "Opus 5.5"}
METRICS = {"brier": brier, "auroc": auroc}
PC = pd.read_csv(f"{OUT}/platt_constrained.csv")


def matrix(task, model, arm, k):
    """draws x 300 predictions; zero-shot is one run repeated for each draw (as compare_ci.py)."""
    if arm == "platt":
        g = PC[(PC.task == task) & (PC.model == model) & (PC.k == k)]
    else:
        P = pd.read_csv(f"{OUT}/{MODELS[model]}_{task}.csv")
        g = P[(P.arm == arm) & (P.k == k)]
    if arm == "zero_shot":
        return np.repeat(g.sort_values("i").p.values[None], len(DRAWS), 0)
    M = g[g.draw.isin(DRAWS)].pivot(index="draw", columns="i", values="p")
    assert list(M.index) == DRAWS and M.shape[1] == 300, (task, model, arm, k)
    return M.values


def main():
    L = ["# Jev vs Gemini 3.8 Flash vs Opus 5.5 — mean predicted probability (AUROC)", "",
         "k cells: **in-context | Platt (constrained: falls back to a base-rate shift when the fit is flat or inverted)**. "
         "Draws 0–1; same examples and 300 test cases. LLMs state probabilities, 25 cases per request (a one-case-per-request "
         "check changed little); Jev returns probabilities natively. Opus ran partly via OpenRouter (same model, same price).",
         "", "Generated by `compare_opus.py` (CIs: `results/v1/compare_opus_ci.csv`).", ""]
    rows, brier_tab = [], []
    for task in TASK_ORDER:
        y = load(task)[1].label.values.astype(int)
        n = len(y)
        rng = np.random.default_rng(0)
        I = rng.integers(0, n, (B, n))
        J = rng.integers(0, len(DRAWS), (B, len(DRAWS)))
        yb = y[I]
        L += [f"### {task} — true rate **{y.mean():.2f}**", "",
              "| model | k=0 | " + " | ".join(f"k={k}" for k in KS) + " |", "|---|---|" + "---|" * len(KS)]
        mats = {}
        for m in MODELS:
            mats[(m, "zero_shot", 0)] = matrix(task, m, "zero_shot", 0)
            for k in KS:
                for arm in ("in_context", "platt"):
                    mats[(m, arm, k)] = matrix(task, m, arm, k)

            def cell(M):
                return f"{M.mean():.2f} ({auroc(M, y[None]).mean():.2f})"
            cells = [cell(mats[(m, "zero_shot", 0)])]
            cells += [f"{cell(mats[(m, 'in_context', k)])} \\| {cell(mats[(m, 'platt', k)])}" for k in KS]
            L.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")
        L.append("")

        # bootstrap at k=0 (zero-shot) and k=100 (in-context, constrained Platt)
        cells_bs = [("zero_shot", 0), ("in_context", 100), ("platt", 100)]
        boot, point = {}, {}
        for m in MODELS:
            for arm, k in cells_bs:
                M = mats[(m, arm, k)]
                for met, f in METRICS.items():
                    per = f(M[:, I], yb[None])
                    boot[(m, arm, met)] = per[J.T, np.arange(B)].mean(0)
                    point[(m, arm, met)] = f(M, y[None]).mean()
                    b = boot[(m, arm, met)]
                    rows.append(dict(task=task, k=k, arm=arm, metric=met, kind="value", a=m, b="",
                                     est=point[(m, arm, met)], lo=np.percentile(b, 2.5), hi=np.percentile(b, 97.5)))
        for arm, k in cells_bs:
            for met in METRICS:
                for other in ("Jev", "Gemini"):
                    d = boot[("Opus", arm, met)] - boot[(other, arm, met)]
                    rows.append(dict(task=task, k=k, arm=arm, metric=met, kind=f"opus_minus_{other.lower()}", a="Opus",
                                     b=other, est=point[("Opus", arm, met)] - point[(other, arm, met)],
                                     lo=np.percentile(d, 2.5), hi=np.percentile(d, 97.5)))
    R = pd.DataFrame(rows)
    R["sig"] = ((R.lo > 0) | (R.hi < 0)) & (R.kind != "value")
    R["n_draws"] = len(DRAWS)
    R.to_csv(f"{OUT}/compare_opus_ci.csv", index=False)

    # Brier table
    V = R[R.kind == "value"].set_index(["task", "arm", "metric", "a"]).est
    D = R[R.kind != "value"].set_index(["task", "arm", "metric", "b"])

    def diff(task, arm, met, other, nd=3):
        r = D.loc[(task, arm, met, other)]
        s = f"{r.est:+.{nd}f} [{r.lo:+.{nd}f}, {r.hi:+.{nd}f}]"
        return f"**{s}**" if r.sig else s

    L += ["## Brier with paired bootstrap 95% CIs (k=0 and k=100)", "",
          f"Cells: Brier Jev / Gemini / Opus; then Opus − Jev and Opus − Gemini [95% CI] (B={B}, test cases and draws "
          "resampled jointly). Negative = Opus better. **Bold** = CI excludes 0.", ""]
    for arm, k, lab in [("zero_shot", 0, "k=0 (zero-shot)"), ("in_context", 100, "k=100, in-context"),
                        ("platt", 100, "k=100, constrained Platt")]:
        L += [f"**{lab}**", "", "| task | Jev / Gemini / Opus | Opus − Jev | Opus − Gemini |", "|---|---|---|---|"]
        for task in TASK_ORDER:
            v = "/".join(f"{V[(task, arm, 'brier', m)]:.3f}" for m in MODELS)
            L.append(f"| {task} | {v} | {diff(task, arm, 'brier', 'Jev')} | {diff(task, arm, 'brier', 'Gemini')} |")
        L.append("")

    L += ["## Summary: tasks (of 8) where Opus is significantly better / worse", "",
          "| metric | cell | vs Jev: better / worse | vs Gemini: better / worse |", "|---|---|---|---|"]
    for met in METRICS:
        for arm, k in [("zero_shot", 0), ("in_context", 100), ("platt", 100)][:3 if met == "brier" else 2]:
            cells = []
            for other in ("Jev", "Gemini"):
                g = R[(R.kind == f"opus_minus_{other.lower()}") & (R.metric == met) & (R.arm == arm)]
                better = (g.hi < 0) if met == "brier" else (g.lo > 0)
                worse = (g.lo > 0) if met == "brier" else (g.hi < 0)
                cells.append(f"{better.sum()} ({','.join(g[better].task) or '–'}) / {worse.sum()} ({','.join(g[worse].task) or '–'})")
            L.append(f"| {met} | {arm} k={k} | " + " | ".join(cells) + " |")
    L += ["", "Constrained Platt is monotone increasing (positive slope or a shift), so its AUROC equals the zero-shot "
          "AUROC and is not repeated.", ""]
    open(f"{OUT}/compare_3models.md", "w").write("\n".join(L))
    return R


if __name__ == "__main__":
    main()
    print("wrote results/v1/compare_3models.md, results/v1/compare_opus_ci.csv")
